#!/usr/bin/env bash
# Regenerates cloudflare.conf from the ranges Cloudflare publishes. Run it on a machine with
# internet access before going live behind Cloudflare, and again whenever Cloudflare announces a
# change (check yearly): an edge address missing here puts that edge's visitors back in one shared
# login rate-limit bucket. Then `docker compose -f docker-compose.prod.yml restart proxy`.
set -euo pipefail
here="$(cd "$(dirname "$0")" && pwd)"
v4="$(curl -fsS https://www.cloudflare.com/ips-v4)"
v6="$(curl -fsS https://www.cloudflare.com/ips-v6)"
# Refuse an empty or odd answer rather than write a file that trusts nothing (or garbage).
grep -Eq '^[0-9.]+/[0-9]+$' <<<"$(head -n1 <<<"$v4")" || { echo "unexpected ips-v4 answer" >&2; exit 1; }
grep -Eq '^[0-9a-f:]+/[0-9]+$' <<<"$(head -n1 <<<"$v6")" || { echo "unexpected ips-v6 answer" >&2; exit 1; }
{
  cat <<HEADER
# EDGE_PROXY=cloudflare — Method A of docs/architecture/cloudflare-integration-guide.md (DNS proxied
# through Cloudflare, "orange cloud").
#
# Behind Cloudflare the TCP peer is a Cloudflare edge server, never the visitor, so without this every
# visitor shared one login rate-limit bucket (ADR-0016) and the audit log recorded Cloudflare's
# addresses (ADR-0027) — security review of ADR-0029, L6. nginx takes the visitor's address from
# CF-Connecting-IP **only when the peer is one of the ranges below**: a client connecting to the
# server directly cannot choose its address by sending the header, because its own address is not
# in the list.
#
# Generated by update-cloudflare.sh on $(date -u +%Y-%m-%d) from https://www.cloudflare.com/ips-v4
# and /ips-v6. Run it again yearly, or when Cloudflare announces a change.
HEADER
  echo "real_ip_header    CF-Connecting-IP;"
  while read -r r; do [ -n "$r" ] && echo "set_real_ip_from  $r;"; done <<<"$v4"
  while read -r r; do [ -n "$r" ] && echo "set_real_ip_from  $r;"; done <<<"$v6"
} > "$here/cloudflare.conf.new"
mv "$here/cloudflare.conf.new" "$here/cloudflare.conf"
echo "Wrote $here/cloudflare.conf ($(grep -c set_real_ip_from "$here/cloudflare.conf") ranges)."
